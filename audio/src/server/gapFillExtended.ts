const DIGIT_MAP: Record<string, string> = {
  '0': 'zero',
  '1': 'one',
  '2': 'two',
  '3': 'three',
  '4': 'four',
  '5': 'five',
  '6': 'six',
  '7': 'seven',
  '8': 'eight',
  '9': 'niner',
};

function speakDigits(val: string): string {
  return val
    .split('')
    .map((ch) => (ch === '.' ? 'decimal' : DIGIT_MAP[ch] ?? ch))
    .join(' ');
}

function speakRunway(rwy: string): string {
  const m = rwy.match(/^(\d{2})([LRC])?$/i);
  if (!m) return rwy;
  const suffix =
    m[2]?.toUpperCase() === 'L'
      ? ' left'
      : m[2]?.toUpperCase() === 'R'
        ? ' right'
        : m[2]?.toUpperCase() === 'C'
          ? ' center'
          : '';
  return `${speakDigits(m[1])}${suffix}`;
}

function runwayVariants(rwy: string): string[] {
  const out = [rwy, rwy.toLowerCase()];
  const m = rwy.match(/^(\d{2})([LRC])?$/i);
  if (m) {
    const num = m[1];
    const side = m[2]?.toUpperCase();
    const shortNum = num.startsWith('0') ? num.slice(1) : num;
    if (side === 'L') {
      out.push(`${num} left`, `${shortNum}L`, `${shortNum} left`, speakRunway(rwy));
    } else if (side === 'R') {
      out.push(`${num} right`, `${shortNum}R`, `${shortNum} right`, speakRunway(rwy));
    } else if (side === 'C') {
      out.push(`${num} center`, `${num} centre`, `${shortNum}C`, speakRunway(rwy));
    } else {
      out.push(shortNum, speakRunway(rwy));
    }
  }
  return Array.from(new Set(out));
}

function speakTaxiway(twy: string): string {
  return twy
    .split('')
    .map((ch) => NATO_MAP[ch.toUpperCase()] ?? DIGIT_MAP[ch] ?? ch)
    .join(' ');
}

function taxiwayVariants(twy: string): string[] {
  const spoken = speakTaxiway(twy);
  return Array.from(new Set([twy, twy.toLowerCase(), spoken, spoken.toLowerCase()]));
}

function speakFlightLevel(fl: string): string {
  const digits = fl.replace(/^FL/i, '');
  return `flight level ${speakDigits(digits)}`;
}

